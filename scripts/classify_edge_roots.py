def main() -> int:
    records = [json.loads(line) for line in IN_JSONL.read_text(encoding="utf-8").splitlines()]

    buckets: dict[str, list[dict]] = {
        "REF": [], "DEF": [], "STATIVE": [], "AMBIGUOUS": [], "ACTION": [],
    }
    for rec in records:
        root = rec["root"]
        if root in REF_ROOTS:
            buckets["REF"].append(rec)
        elif root in DEF_ROOTS:
            buckets["DEF"].append(rec)
        elif root in STATIVE_ROOTS:
            buckets["STATIVE"].append(rec)
        elif root in AMBIGUOUS_ROOTS:
            buckets["AMBIGUOUS"].append(rec)
        else:
            buckets["ACTION"].append(rec)

    for name, recs in buckets.items():
        out_path = OUT_DIR / f"verb_roots_{name.lower()}.jsonl"
        with out_path.open("w", encoding="utf-8") as f:
            for rec in recs:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    total_groups = len(records)
    total_count = sum(r["count"] for r in records)
    print(f"전체: {total_groups}개 그룹 / {total_count}회")
    for name, recs in buckets.items():
        n = len(recs)
        c = sum(r["count"] for r in recs)
        print(f"  {name:8s}: {n:4d}개 그룹 ({n/total_groups:5.1%}) / {c:6d}회 ({c/total_count:5.1%})")

    unmatched_curated = (REF_ROOTS | DEF_ROOTS | STATIVE_ROOTS | AMBIGUOUS_ROOTS) - {
        r["root"] for r in records
    }
    if unmatched_curated:
        print(f"\n경고: curated list에 있지만 verb_groups.jsonl에 없는 어근: {sorted(unmatched_curated)}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
